export function calculateMacrosForGrams(
  caloriesPer100g: number,
  proteinPer100g: number,
  carbsPer100g: number,
  fatPer100g: number,
  grams: number
) {
  const safeGrams = Math.max(0, grams || 0);
  const ratio = safeGrams / 100;
  return {
    calories: Math.round(caloriesPer100g * ratio),
    protein: Math.round(proteinPer100g * ratio * 10) / 10,
    carbs: Math.round(carbsPer100g * ratio * 10) / 10,
    fat: Math.round(fatPer100g * ratio * 10) / 10,
  };
}

export const FOOD_LIBRARY: LibraryFoodItem[] = RAW_FOODS.map((item) => {
  const computed = calculateMacrosForGrams(
    item.caloriesPer100g,
    item.proteinPer100g,
    item.carbsPer100g,
    item.fatPer100g,
    item.defaultGrams
  );
  return {
    ...item,
    calories: computed.calories,
    protein: computed.protein,
    carbs: computed.carbs,
    fat: computed.fat,
  };
});
